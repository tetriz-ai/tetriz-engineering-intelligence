// Command scan-text-for-ai-signatures scans commit messages, pull-request
// descriptions and review comments for the signatures AI coding tools leave.
//
//	go run ./examples/scan-text-for-ai-signatures
//
// It needs nothing but the text. A tool's footer or co-author trailer names it;
// a header that claims AI authorship without naming a known tool counts as
// ai-unknown.
package main

import (
	"fmt"
	"strings"

	"github.com/tetriz-ai/tetriz-engineering-intelligence/attribution/signature"
)

func main() {
	commits := []string{
		"fix: retry on 503\n\nCo-authored-by: Claude <noreply@anthropic.com>",
		"feat: add a limiter\n\nCo-authored-by: Jane Doe <jane@example.com>",
	}
	for _, c := range commits {
		show("commit", lastLine(c), signature.ScanCommitMessage(c))
	}

	descriptions := []string{
		"Adds a token bucket.\n\nGenerated by Copilot",
		"Adds a token bucket.\n\nTested by hand.",
	}
	for _, d := range descriptions {
		show("pull request", lastLine(d), signature.ScanPRDescription(d))
	}

	reviews := []string{
		"## Kiro AI Review\n\nTwo issues below.",
		"Reviewer: Someothertool AI\n\nExtract this helper.",
		"Looks good to me.",
	}
	for _, r := range reviews {
		show("review", firstLine(r), signature.ScanReviewBody(r))
	}

	all := signature.MergeAttributions(
		signature.ScanCommitMessage(commits[0]),
		signature.ScanPRDescription(descriptions[0]),
	)
	fmt.Printf("\nmerged: %v %v\n", all.IsAIAttributed, all.Sources)
}

// show prints the line of the text that carries the signature, and the result.
func show(kind, line string, a signature.AIAttribution) {
	fmt.Printf("%-13s %-48q %-5v %v\n", kind, line, a.IsAIAttributed, a.Sources)
}

func firstLine(s string) string { return strings.SplitN(s, "\n", 2)[0] }

func lastLine(s string) string { return s[strings.LastIndex(s, "\n")+1:] }

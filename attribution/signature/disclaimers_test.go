// Declined: an "AI Model:" header counts as AI whatever its
// value, so a disclosure field holding a disclaimer or a placeholder is counted.
func TestAnAIModelHeaderCountsWhateverItsValueDeclined(t *testing.T) {
	for _, body := range []string{
		"AI model: none",
		"AI Model: N/A",
		"**AI model:** not used",
		"AI Model: nothing",
		"AI Model: false",
		"AI model: n.a.",
		"AI model: did not use one",
	} {
		assert.Equal(t, []string{SourceAIUnknown}, ScanPRDescription(body).Sources, body)
		assert.Equal(t, []string{SourceAIUnknown}, ScanReviewBody(body).Sources, body)
	}
}

// Declined: a Claude Code footer that links to a host other than claude.com,
// and "GitHub Copilot" named in full, are not recognised. The footer linking to
// claude.com, and the bare claude.com link, are.
func TestFooterVariantsAreMissedDeclined(t *testing.T) {
	for _, body := range []string{
		"Adds retries.\n\nGenerated with [Claude Code](https://example.com/claude-code)",
		"Adds retries.\n\nGenerated by GitHub Copilot",
	} {
		assert.False(t, ScanPRDescription(body).IsAIAttributed, body)
	}
	for _, body := range []string{
		"Adds retries.\n\nGenerated with [Claude Code](https://claude.com/claude-code)",
		"Adds retries.\n\nhttps://claude.com/claude-code",
	} {
		assert.Equal(t, []string{SourceClaudeCode}, ScanPRDescription(body).Sources, body)
	}
}

// Declined: a sentence that denies machine authorship still
// counts, because the pattern does not look at the words before it.
func TestADeniedGeneratorStillCountsDeclined(t *testing.T) {
	assert.Equal(t, []string{SourceClaudeCode}, ScanPRDescription("This change was not generated with Claude Code.").Sources)
	assert.Equal(t, []string{SourceCopilot}, ScanPRDescription("Not generated by Copilot, written by hand.").Sources)
}

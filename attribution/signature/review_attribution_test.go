// TestScanReviewBodyAttributionHeaders runs the detector against the header shapes AI
// reviewers sign review comments with. A closed vendor list with a single preposition
// grades every one of these human, so this table is the record of what that list misses.
func TestScanReviewBodyAttributionHeaders(t *testing.T) {
	t.Parallel()
	tests := []struct {
		name           string
		body           string
		wantAttributed bool
		wantSources    []string
	}{
		{
			// The one-preposition miss: the pattern accepted only "generated with".
			name:           "PR Review generated BY Claude Code",
			body:           "**PR Review - Generated by Claude Code**\n\nAI Model: Claude Sonnet 5\n\nLooks good overall.",
			wantAttributed: true,
			wantSources:    []string{SourceClaudeCode},
		},
		{
			name:           "generated with Claude Code still matches",
			body:           "**PR Review - Generated with Claude Code**",
			wantAttributed: true,
			wantSources:    []string{SourceClaudeCode},
		},
		{
			name:           "PR Review generated by Kiro AI",
			body:           "**PR Review - Generated by Kiro AI**\n\nAI Model: Claude Opus 4.5\n\n## Findings",
			wantAttributed: true,
			wantSources:    []string{SourceKiro},
		},
		{
			name:           "Kiro AI review heading",
			body:           "## Kiro AI Review — PR #21\n\nTwo issues below.",
			wantAttributed: true,
			wantSources:    []string{SourceKiro},
		},
		{
			name:           "AI Model header alone",
			body:           "Review complete.\n\nAI Model: some-model-we-have-never-heard-of",
			wantAttributed: true,
			wantSources:    []string{SourceAIUnknown},
		},
		{
			name:           "Reviewer X AI with an unknown vendor",
			body:           "Reviewer: Someothertool AI\n\nSuggestion: extract this helper.",
			wantAttributed: true,
			wantSources:    []string{SourceAIUnknown},
		},
		{
			name:           "generated by an unknown X AI",
			body:           "Generated by Someothertool AI",
			wantAttributed: true,
			wantSources:    []string{SourceAIUnknown},
		},
		{
			// A multi-word vendor name, which a single-token wildcard would miss.
			name:           "generated by a multi-word unknown vendor",
			body:           "Generated by Amazon Q AI",
			wantAttributed: true,
			wantSources:    []string{SourceAIUnknown},
		},
		{
			// A disclaimer must not mask a real attribution later in the same body —
			// every occurrence is vetted, not only the first match. Both occurrences here
			// are UNNAMED vendors, so this is reachable only through the vendor-attribution
			// loop; a named vendor would be caught by prPatterns before that loop runs and
			// would pass whether or not the loop vets past the first match.
			name:           "a real attribution after a disclaimer still counts",
			body:           "Reviewer: Not AI for the first pass.\n\nReviewer: Someothertool AI",
			wantAttributed: true,
			wantSources:    []string{SourceAIUnknown},
		},
		{
			// A real product whose name opens with a stop word. Vetting only the capture's
			// first word would reject this outright.
			name:           "multi-word vendor whose first word is a stop word",
			body:           "Generated by New Relic AI",
			wantAttributed: true,
			wantSources:    []string{SourceAIUnknown},
		},
		{
			// A named vendor wins over the generic fallback — one review, one source,
			// never double-counted.
			name:           "named vendor beats the unknown fallback",
			body:           "**PR Review - Generated by Claude Code**\n\nReviewer: Claude AI\n\nAI Model: Claude Sonnet 5",
			wantAttributed: true,
			wantSources:    []string{SourceClaudeCode},
		},
	}

	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			t.Parallel()
			result := ScanReviewBody(tt.body)
			assert.Equal(t, tt.wantAttributed, result.IsAIAttributed, "IsAIAttributed")
			assert.Equal(t, tt.wantSources, result.Sources, "Sources")
		})
	}
}

// TestScanReviewBodyMachineGeneratedIsNotAI pins the deliberate boundary of the
// generator-agnostic sweep: a header asserting only that a review was machine-GENERATED is
// not evidence of AI. Non-AI review and lint bots sign exactly that way, so counting them
// would inflate AI adoption with ordinary CI.
//
// The cost is real and is recorded here rather than hidden: the last two bodies are the
// shape of AI-harness reviews that identify themselves only as "Automated", and they go
// undetected. Catching them needs a signal that distinguishes an
// AI harness from a lint bot, which none of these headers carry.
func TestScanReviewBodyMachineGeneratedIsNotAI(t *testing.T) {
	t.Parallel()
	generatedButNotAI := []string{
		// Non-AI tooling — must not be counted as AI.
		"**PR Review - Generated by Danger**",
		"Code Review: Generated by SonarQube",
		"Reviewer: Automated (SonarQube)",
		// Real AI harnesses that state only "Automated" — accepted misses.
		"- Reviewer: Automated (review-bot)\n\nBLOCKER: unbounded query.",
		"## Design-conformance review (automated; no approval, a human owns the merge)\n\nReviewer: Automated",
	}

	for _, body := range generatedButNotAI {
		t.Run(body, func(t *testing.T) {
			t.Parallel()
			result := ScanReviewBody(body)
			assert.False(t, result.IsAIAttributed,
				"a machine-generated header that does not claim AI must not be attributed (sources=%v): %q", result.Sources, body)
		})
	}
}

// TestScanReviewBodyHumanCorpusStaysClean is the false-positive guard, and it is what
// makes the additions above a detector fix rather than a broadened heuristic. These are
// the shapes of ordinary human review comments — short, direct, and often *about* AI or
// review tooling. A body that merely discusses AI asserts nothing about who wrote it, and
// must stay unattributed.
func TestScanReviewBodyHumanCorpusStaysClean(t *testing.T) {
	t.Parallel()
	humanComments := []string{
		"LGTM, please add a unit test before merging.",
		"nit: rename this to `handler`.",
		"Move your cursor before the close brace.",
		"Can we use an AI review tool on this repo?",
		"I think the AI model choice here is wrong — gpt-4 would be cheaper.",
		"Generated files should not be edited by hand.",
		"This was generated by the codegen script, not by a person.",
		"Reviewer assignment is automated in this repo via CODEOWNERS.",
		"Why this is risky: the query is unbounded.",
		"BLOCKER: this drops the tenant scope.",
		"Please review by Friday.",
		"copilot suggested this but I rewrote it",
		"windsurf keeps reformatting this file",
		"See the AI model comparison doc for context.",
		"reviewer: me",
		// A human explicitly disclaiming or discussing AI authorship — the phrasings a
		// case-insensitive single-token wildcard reads as machine authorship. Both cases
		// are listed because ordinary sentence-case puts a capital exactly where a vendor
		// name would sit, so requiring a capital does not by itself separate them.
		"Reviewer: not AI",
		"Reviewer: Not AI",
		"Reviewer: No AI was used",
		"Reviewer: No AI, reviewed by hand.",
		"reviewer: the AI failed here, adding my own note.",
		"Reviewer: The AI failed here, adding my own note.",
		"Generated by The AI",
		"Generated by our AI",
		"Generated by Our AI",
		"Reviewer: A human",
		"Reviewer: My AI experiments are unrelated to this PR",
		"Reviewer: Nobody AI",
		"Generated by The New AI",
		// Merely naming a vendor is not an attribution claim.
		"Should we try Kiro AI for automated reviews next quarter?",
		"Kiro AI has been flaky lately, can we disable it?",
	}

	for _, body := range humanComments {
		t.Run(body, func(t *testing.T) {
			t.Parallel()
			result := ScanReviewBody(body)
			assert.False(t, result.IsAIAttributed,
				"human comment must not be attributed to AI (sources=%v): %q", result.Sources, body)
		})
	}
}

// TestScanPRDescriptionSharesTheFix pins that both prepositions are accepted on every
// surface. prPatterns is the shared set behind both PR descriptions and review bodies,
// whichever forge they come from.
func TestScanPRDescriptionSharesTheFix(t *testing.T) {
	t.Parallel()
	tests := []struct {
		name        string
		body        string
		wantSources []string
	}{
		{
			name:        "generated by Claude Code in a PR description",
			body:        "## Summary\n\nGenerated by Claude Code",
			wantSources: []string{SourceClaudeCode},
		},
		{
			// The mirror-image brittleness: Copilot's pattern pinned "by".
			name:        "generated with Copilot in a PR description",
			body:        "Generated with Copilot",
			wantSources: []string{SourceCopilot},
		},
		{
			name:        "generated by Copilot still matches",
			body:        "Generated by Copilot",
			wantSources: []string{SourceCopilot},
		},
		{
			name:        "emoji footer with by",
			body:        "🤖 Generated by [Claude Code](https://claude.com/claude-code)",
			wantSources: []string{SourceClaudeCode},
		},
		{
			// The emoji footer must cross markdown emphasis without a URL to fall back on.
			name:        "emoji footer with emphasised tool name",
			body:        "🤖 Generated with **Claude Code**",
			wantSources: []string{SourceClaudeCode},
		},
		{
			// The emoji and preposition are shared vocabulary: attributing this to Claude
			// Code as well as Copilot would double-count one review across two tools.
			name:        "emoji footer naming a different tool is not Claude Code",
			body:        "🤖 Generated with Copilot",
			wantSources: []string{SourceCopilot},
		},
		{
			name:        "cursor bugbot generated-by variant",
			body:        "Generated by Cursor Bugbot",
			wantSources: []string{SourceCursorBot},
		},
		{
			name:        "unknown generator in a PR description",
			body:        "AI Model: mystery-model-v3",
			wantSources: []string{SourceAIUnknown},
		},
	}

	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			t.Parallel()
			result := ScanPRDescription(tt.body)
			assert.True(t, result.IsAIAttributed, "IsAIAttributed")
			assert.Equal(t, tt.wantSources, result.Sources, "Sources")
		})
	}
}

// TestScanCommitMessageUnchangedByProseFallback pins the boundary of this change. Commit
// messages are matched on the co-author trailer convention, which does not have the
// preposition ambiguity, so they do not take the prose fallback — an "AI Model:" line in
// a commit message is not an attribution signal there.
func TestScanCommitMessageUnchangedByProseFallback(t *testing.T) {
	t.Parallel()
	result := ScanCommitMessage("fix: bound the query\n\nAI Model: mystery-model-v3")
	assert.False(t, result.IsAIAttributed,
		"commit-message scanning is trailer-based and must not pick up the prose fallback")

	trailer := ScanCommitMessage("fix: bound the query\n\nCo-authored-by: Claude <noreply@anthropic.com>")
	assert.True(t, trailer.IsAIAttributed, "the trailer convention must still attribute")
	assert.Equal(t, []string{SourceClaudeCode}, trailer.Sources)
}

// Package signature reports whether commit, pull-request or review text carries
// the signature an AI coding tool leaves, and which tool left it.
package signature

import (
	"regexp"
	"strings"
)

// AIAttribution holds the result of scanning text for AI tool signatures.
type AIAttribution struct {
	IsAIAttributed bool
	Sources        []string // deduplicated, e.g. ["claude-code", "copilot", "cursor-bugbot"]
}

// The Source constants are the values AIAttribution.Sources holds.
const (
	SourceClaudeCode = "claude-code"
	SourceCopilot    = "copilot"
	SourceCursor     = "cursor"
	SourceCursorBot  = "cursor-bugbot"
	SourceCodeium    = "codeium"
	SourceWindsurf   = "windsurf"
	SourceKiro       = "kiro"
	// SourceAIUnknown attributes text that states machine authorship without naming a
	// tool this package knows. A named-vendor list can only ever recognise the tools
	// that existed when it was written, and its failure mode is silent — an
	// unrecognised reviewer degrades to "no AI here", which is indistinguishable from
	// a genuinely human-reviewed org. This source keeps such a review counted as AI
	// while being honest that the generator is unidentified.
	SourceAIUnknown = "ai-unknown"
)

// pattern pairs: compiled regex → source label.
type signaturePattern struct {
	re     *regexp.Regexp
	source string
}

// commitPatterns are checked against commit messages.
// Order matters: more specific patterns first.
var commitPatterns = []signaturePattern{
	// Claude Code — match on anthropic email or "Claude" in co-author name.
	{regexp.MustCompile(`(?i)co-authored-by:.*noreply@anthropic\.com`), SourceClaudeCode},
	{regexp.MustCompile(`(?i)co-authored-by:.*\bclaude\b`), SourceClaudeCode},
	// GitHub Copilot — match on "Copilot" in co-author name.
	{regexp.MustCompile(`(?i)co-authored-by:.*\bcopilot\b`), SourceCopilot},
	// Cursor — co-author header.
	{regexp.MustCompile(`(?i)co-authored-by:.*\bcursor\b`), SourceCursor},
	// Cursor Bugbot — HTML comment block (appears in commit messages too).
	{regexp.MustCompile(`(?i)<!--\s*CURSOR_SUMMARY\s*-->`), SourceCursorBot},
	// Codeium.
	{regexp.MustCompile(`(?i)co-authored-by:.*\bcodeium\b`), SourceCodeium},
	// Windsurf.
	{regexp.MustCompile(`(?i)co-authored-by:.*\bwindsurf\b`), SourceWindsurf},
}

// prPatterns are checked against PR/MR descriptions.
// Includes both footer-style patterns AND co-author patterns, because
// PR descriptions may contain co-authored-by lines (not just commit messages).
// A prose attribution names the tool but not a fixed preposition — real bodies say
// "Generated with X" and "Generated by X" interchangeably, so every prose pattern below
// accepts both. Pinning one preposition is a single-word false negative: it reads as
// working (the pattern matches the phrasing its author happened to see) while missing an
// equally common one, with no signal that anything was dropped.
const generatedPrefix = `generated\s+(?:with|by)\s+`

var prPatterns = []signaturePattern{
	// Cursor Bugbot block.
	{regexp.MustCompile(`(?i)<!--\s*CURSOR_SUMMARY\s*-->`), SourceCursorBot},
	{regexp.MustCompile(`(?i)(?:written|generated)\s+(?:with|by)\s+cursor\s+bugbot`), SourceCursorBot},
	// Claude Code footer URL — robust to markdown link wrapping and emoji
	// variance that the prose patterns below miss.
	{regexp.MustCompile(`(?i)claude\.com/claude-code`), SourceClaudeCode},
	{regexp.MustCompile(`(?i)` + generatedPrefix + `claude\s+code`), SourceClaudeCode},
	// The emoji footer names its tool through markdown punctuation the prose pattern
	// above cannot cross ("[Claude Code](…)", "**Claude Code**"), so it tolerates that
	// punctuation — but it must still require the tool: the emoji and preposition alone
	// are shared vocabulary, and "🤖 Generated with Copilot" would otherwise be
	// attributed to Claude Code as well as Copilot.
	{regexp.MustCompile(`(?i)🤖\s*` + generatedPrefix + `\W*claude\b`), SourceClaudeCode},
	{regexp.MustCompile(`(?i)co-authored-by:.*noreply@anthropic\.com`), SourceClaudeCode},
	{regexp.MustCompile(`(?i)co-authored-by:.*\bclaude\b`), SourceClaudeCode},
	// Copilot.
	{regexp.MustCompile(`(?i)` + generatedPrefix + `copilot`), SourceCopilot},
	{regexp.MustCompile(`(?i)co-authored-by:.*\bcopilot\b`), SourceCopilot},
	// Kiro — a third-party AI reviewer that posts through a user OAuth account. Anchored
	// to the three attribution contexts it signs with, exactly like every other vendor
	// here: a bare vendor-name match would attribute any human sentence that merely
	// mentions the tool ("does Kiro AI review this repo too?").
	{regexp.MustCompile(`(?i)` + generatedPrefix + `kiro\s+ai\b`), SourceKiro},
	{regexp.MustCompile(`(?im)^\s*#{1,6}\s*\**\s*kiro\s+ai\b`), SourceKiro},
	{regexp.MustCompile(`(?i)\breviewer\s*:\s*\**\s*kiro\s+ai\b`), SourceKiro},
	// Cursor co-author.
	{regexp.MustCompile(`(?i)co-authored-by:.*\bcursor\b`), SourceCursor},
	// Codeium co-author.
	{regexp.MustCompile(`(?i)co-authored-by:.*\bcodeium\b`), SourceCodeium},
	// Windsurf co-author.
	{regexp.MustCompile(`(?i)co-authored-by:.*\bwindsurf\b`), SourceWindsurf},
}

// explicitAIAttributionPatterns match text that ASSERTS machine authorship without
// naming a tool [prPatterns] knows. They are deliberately generator-agnostic: the
// wildcard sits where the tool name goes, so a reviewer that did not exist when this was
// written is still recognised.
//
// Each is a structured attribution header, not an inference from writing style. That
// boundary is what keeps the false-positive rate near zero: a human discussing AI in
// prose ("we should try an AI review here") asserts nothing about who wrote the text,
// and a corpus of ordinary short human review comments scores zero against these.
// Detecting an unattributed machine template by its shape alone is a different and much
// riskier class of inference, and is deliberately not done here — an AI reviewer that
// states nothing about itself is not detected.
//
// Every pattern requires the word "ai" to appear as part of the claim. A header asserting
// only that a review was machine-GENERATED ("PR Review - Generated by <X>",
// "Reviewer: Automated") is not evidence of AI: non-AI review and lint bots (SonarQube,
// Danger, CODEOWNERS automation) sign exactly that way, and counting them would inflate
// AI adoption with ordinary CI. The cost is a real miss — an AI harness that calls itself
// only "Automated" is not detected — which is the correct direction to err for a metric
// that answers "how much review is AI-assisted".
//
// The generator name must be Capitalized. These are proper nouns in the headers that
// carry them, and requiring the capital is what separates "Reviewer: Kiro AI" from
// "Reviewer: not AI" and "reviewer: the AI failed here" — human phrasings, in this exact
// domain, that a case-insensitive single-token wildcard reads as machine authorship.
var explicitAIAttributionPatterns = []*regexp.Regexp{
	// "AI Model: Claude Sonnet 5" — anchored to a line so it reads as a header field
	// rather than prose that happens to mention a model. It has no vendor slot, so no
	// disclaimer can occupy one.
	regexp.MustCompile(`(?im)^\s*\**\s*ai\s+model\s*\**\s*:`),
}

// aiVendorAttributionPatterns claim authorship by NAMING a generator, so each captures
// that name in group 1 for [namesAVendor] to vet. A capture plus a check, rather than a
// cleverer regex, because RE2 has no negative lookahead — and the thing that must be
// excluded is a word class, not a shape.
var aiVendorAttributionPatterns = []*regexp.Regexp{
	// "Reviewer: Kiro AI", "Reviewer: Claude AI", "Reviewer: Amazon Q AI".
	regexp.MustCompile(`(?i:reviewer)\s*:\s*\**\s*(` + aiVendorName + `)\s+(?i:ai)\b`),
	// "Generated by Kiro AI" — the tool is unknown but "<X> AI" is an authorship claim.
	regexp.MustCompile(`(?i:generated)\s+(?i:with|by)\s+(` + aiVendorName + `)\s+(?i:ai)\b`),
}

// aiVendorName matches a Capitalized generator name of up to three words, so a
// multi-word vendor ("Amazon Q AI") is recognised rather than silently missed.
const aiVendorName = `[A-Z][\w.-]*(?:\s+[A-Z][\w.-]*){0,2}`

// aiVendorStopWords are words that fit the vendor slot but name no vendor. Requiring a
// capital is not enough on its own: ordinary sentence-case human text puts one there —
// "Reviewer: Not AI", "Reviewer: No AI was used", "Generated by The AI" — and each of those
// is a human DISCLAIMING AI, the exact opposite of what matching them would record. Listed
// lower-case and compared case-insensitively so the capitalised and un-capitalised forms
// are covered by one entry.
var aiVendorStopWords = map[string]struct{}{
	"a": {}, "all": {}, "an": {}, "another": {}, "any": {}, "both": {}, "each": {},
	"either": {}, "every": {}, "he": {}, "her": {}, "his": {}, "human": {}, "i": {},
	"it": {}, "its": {}, "just": {}, "manual": {}, "manually": {}, "me": {}, "more": {},
	"my": {}, "neither": {}, "never": {}, "new": {}, "no": {}, "nobody": {}, "none": {},
	"nope": {}, "nor": {}, "not": {}, "old": {}, "one": {}, "only": {}, "our": {},
	"real": {}, "same": {}, "she": {}, "some": {}, "that": {}, "the": {}, "their": {},
	"them": {}, "these": {}, "they": {}, "this": {}, "those": {}, "us": {}, "we": {},
	"you": {}, "your": {},
}

// namesAVendor reports whether a captured vendor slot actually names a generator.
//
// A capture is rejected only when EVERY word in it is a stop word. Vetting just the first
// would reject real multi-word vendors whose name happens to open with one — "Generated by
// New Relic AI" names a shipping product, and "New" is a stop word — while the disclaimers
// this exists to catch ("Not AI", "No AI", "The AI") are single stop words by construction.
// A real name contributes at least one word that is not a stop word.
func namesAVendor(captured string) bool {
	words := strings.Fields(captured)
	if len(words) == 0 {
		return false
	}
	for _, word := range words {
		if _, isStopWord := aiVendorStopWords[strings.ToLower(word)]; !isStopWord {
			return true
		}
	}
	return false
}

// scanProse runs the named-vendor patterns and falls back to an explicit-attribution
// sweep, so a body that states machine authorship is never graded human merely because
// its generator is unrecognised. The fallback only applies when no vendor matched —
// a named source is strictly better data than [SourceAIUnknown], and emitting both
// would double-count one review.
func scanProse(text string, patterns []signaturePattern) AIAttribution {
	attributed := scan(text, patterns)
	if attributed.IsAIAttributed {
		return attributed
	}
	for _, re := range explicitAIAttributionPatterns {
		if re.MatchString(text) {
			return AIAttribution{IsAIAttributed: true, Sources: []string{SourceAIUnknown}}
		}
	}
	for _, re := range aiVendorAttributionPatterns {
		// Every occurrence is vetted, not just the first: one disclaimer earlier in a body
		// must not mask a genuine attribution later in it. Scanned incrementally and
		// stopped at the first accepted vendor rather than materialising all matches —
		// review bodies are vendor-supplied and unbounded, and a body dominated by
		// disclaimer-shaped lines would otherwise force a full enumeration on every
		// comment scanned.
		for offset := 0; offset < len(text); {
			loc := re.FindStringSubmatchIndex(text[offset:])
			if loc == nil {
				break
			}
			if namesAVendor(text[offset+loc[2] : offset+loc[3]]) {
				return AIAttribution{IsAIAttributed: true, Sources: []string{SourceAIUnknown}}
			}
			// Advance past this match. loc[1] is its end; guard against a zero-width
			// match (impossible for these patterns, but a silent infinite loop if it
			// ever became possible).
			if loc[1] <= 0 {
				break
			}
			offset += loc[1]
		}
	}
	return attributed
}

// ScanCommitMessage scans a commit message for AI tool signatures.
func ScanCommitMessage(message string) AIAttribution {
	if strings.TrimSpace(message) == "" {
		return AIAttribution{}
	}
	return scan(message, commitPatterns)
}

// ScanPRDescription scans a PR/MR description for AI tool signatures.
func ScanPRDescription(body string) AIAttribution {
	if strings.TrimSpace(body) == "" {
		return AIAttribution{}
	}
	return scanProse(body, prPatterns)
}

// ScanReviewBody scans a code-review body for AI tool signatures, using the same
// patterns as ScanPRDescription. A body that states machine authorship without
// naming a known tool returns SourceAIUnknown.
func ScanReviewBody(body string) AIAttribution {
	if strings.TrimSpace(body) == "" {
		return AIAttribution{}
	}
	return scanProse(body, prPatterns)
}

// MergeAttributions combines multiple attributions, deduplicating sources.
func MergeAttributions(attrs ...AIAttribution) AIAttribution {
	seen := make(map[string]struct{})
	var sources []string
	for _, a := range attrs {
		for _, s := range a.Sources {
			if _, ok := seen[s]; !ok {
				seen[s] = struct{}{}
				sources = append(sources, s)
			}
		}
	}
	return AIAttribution{
		IsAIAttributed: len(sources) > 0,
		Sources:        sources,
	}
}

// DeduplicateSources returns a deduplicated copy of the source list, preserving insertion order.
func DeduplicateSources(sources []string) []string {
	if len(sources) == 0 {
		return nil
	}
	seen := make(map[string]struct{}, len(sources))
	var result []string
	for _, s := range sources {
		s = strings.TrimSpace(s)
		if s == "" {
			continue
		}
		if _, ok := seen[s]; !ok {
			seen[s] = struct{}{}
			result = append(result, s)
		}
	}
	if len(result) == 0 {
		return nil
	}
	return result
}

func scan(text string, patterns []signaturePattern) AIAttribution {
	seen := make(map[string]struct{})
	var sources []string
	for _, p := range patterns {
		if _, ok := seen[p.source]; ok {
			continue // already matched this source
		}
		if p.re.MatchString(text) {
			seen[p.source] = struct{}{}
			sources = append(sources, p.source)
		}
	}
	return AIAttribution{
		IsAIAttributed: len(sources) > 0,
		Sources:        sources,
	}
}

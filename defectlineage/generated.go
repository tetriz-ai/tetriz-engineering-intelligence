package defectlineage

import (
	"bytes"

	enry "github.com/go-enry/go-enry/v2"
)

// Generated and vendored files are kept out of blame because their content is
// not authored: a regenerated protobuf stub out-churns the hand-written change
// that actually fixed the bug, and would out-score it.
//
// The decision is deliberately language-agnostic. go-enry supplies path- and
// content-aware detection across many languages but its coverage is incomplete —
// it misses, for one, generated TypeScript whose banner is present — so the check
// unions go-enry with a banner scan that keys on the cross-language convention
// rather than any one toolchain's file extension.

// markerScanLines bounds how many leading lines the banner scan considers. A
// generated banner sits at the very top of a file by universal convention, so a
// short line window keeps ordinary prose deeper in a file from matching a marker
// by accident.
const markerScanLines = 15

// markerScanBytes bounds the banner scan by bytes as well as lines, so a
// minified generated file whose banner shares one very long leading line is
// still searched — a line-buffered scan would silently drop a line past its
// buffer cap and miss exactly the file this scan exists to catch.
const markerScanBytes = 64 * 1024

// generatedMarkers are the case-insensitive substrings a generated file's banner
// uses across languages. Keyed on the convention, not the extension, which is
// what makes the scan language-agnostic where go-enry's per-language coverage is
// not.
var generatedMarkers = [][]byte{
	[]byte("@generated"),
	[]byte("do not edit"),
	[]byte("code generated"),
	[]byte("generated by"),
	[]byte("autogenerated"),
}

// ContentVerdict reports whether a file is generated and, when it is, which
// signal caught it, so a caller can act on the classification and observe the
// marker-only case distinctly — a hand-written file carrying a banner-like
// phrase go-enry does not recognise surfaces as [VerdictByMarker], the case
// worth watching for over-exclusion.
type ContentVerdict int

const (
	// VerdictNotGenerated means neither go-enry nor the banner scan classified
	// the file as generated.
	VerdictNotGenerated ContentVerdict = iota
	// VerdictByEnry means go-enry classified it generated, by path or content.
	VerdictByEnry
	// VerdictByMarker means go-enry did not, and only the banner scan matched.
	VerdictByMarker
)

// String returns a short stable label for the verdict, suitable as an Observer
// label value.
func (v ContentVerdict) String() string {
	switch v {
	case VerdictByEnry:
		return "enry"
	case VerdictByMarker:
		return "marker"
	default:
		return "not_generated"
	}
}

// Path-exclusion reasons returned by [PathExcludeReason], so a caller can
// observe which signal dropped a path — a vendored tree, or a path-detectable
// generated file. Stable, bounded label values.
const (
	ReasonVendor        = "vendor"
	ReasonGeneratedPath = "generated_path"
)

// PathExcludeReason reports why a path is excluded by the path-only filter —
// [ReasonVendor] or [ReasonGeneratedPath] — or "" when it is not. It lets a
// caller both drop the path and record which signal did it, so over-exclusion at
// the path stage, such as first-party code under a vendor-named directory, is
// measurable rather than a silent zero.
func PathExcludeReason(path string) string {
	if path == "" {
		return ""
	}
	if enry.IsVendor(path) {
		return ReasonVendor
	}
	if enry.IsGenerated(path, nil) {
		return ReasonGeneratedPath
	}
	return ""
}

// ClassifyContent classifies a file using both its path and its body: go-enry's
// content-aware detection, then the banner scan. A caller that already holds the
// content — the blame walk holds it in order to blame the file — uses this to
// drop the generated files a path-only check cannot see, at no extra fetch, and
// to observe the marker-only verdict.
func ClassifyContent(path string, content []byte) ContentVerdict {
	if enry.IsGenerated(path, content) {
		return VerdictByEnry
	}
	if hasGeneratedMarker(content) {
		return VerdictByMarker
	}
	return VerdictNotGenerated
}

// hasGeneratedMarker reports whether a generated banner appears in the file's
// leading window, case-insensitively. The window is bounded on both bytes and
// lines: at most markerScanBytes, so one very long minified leading line is
// still searched, and at most markerScanLines newlines, so an ordinary file's
// window stays near the top. Whichever bound is hit first ends the window; a
// generated banner sits at the very top by convention.
//
// A marker counts only where the banner convention puts it: at the start of a
// line's comment text. Matched anywhere in the window instead, ordinary prose
// trips it — a doc comment reading "summarises the invoice generated by the
// nightly job" classifies a hand-written file as generated, and the blame walk
// then drops the file and reports the fix unattributed, which reads to a caller
// as "we looked and found no culprit".
func hasGeneratedMarker(content []byte) bool {
	if len(content) == 0 {
		return false
	}
	window := content
	if len(window) > markerScanBytes {
		window = window[:markerScanBytes]
	}
	if i := indexNthNewline(window, markerScanLines); i >= 0 {
		window = window[:i]
	}
	for _, line := range bytes.Split(bytes.ToLower(window), []byte("\n")) {
		if lineOpensWithMarker(line) {
			return true
		}
	}
	return false
}

// commentOpeners are the punctuation a banner line may carry before its text.
// Stripped repeatedly, so "/* @generated */" and "// // @generated" both reduce
// to the banner itself.
var commentOpeners = [][]byte{
	[]byte("//"), []byte("/*"), []byte("<!--"), []byte("--"),
	[]byte("#"), []byte("*"), []byte(";"), []byte("%"), []byte("!"),
}

// lineOpensWithMarker reports whether a lower-cased line begins with a generated
// banner once its comment punctuation is stripped.
func lineOpensWithMarker(line []byte) bool {
	t := bytes.TrimSpace(line)
	for stripped := true; stripped; {
		stripped = false
		for _, o := range commentOpeners {
			if bytes.HasPrefix(t, o) {
				t = bytes.TrimSpace(t[len(o):])
				stripped = true
				break
			}
		}
	}
	for _, m := range generatedMarkers {
		if bytes.HasPrefix(t, m) {
			return true
		}
	}
	return false
}

// indexNthNewline returns the index of the nth '\n' in b, or -1 when b holds
// fewer than n newlines.
func indexNthNewline(b []byte, n int) int {
	count := 0
	for i, c := range b {
		if c == '\n' {
			count++
			if count == n {
				return i
			}
		}
	}
	return -1
}

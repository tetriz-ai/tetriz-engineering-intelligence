// TestAnalyzeDiff_RenameOnlyAgreesAcrossFormats proves a rename with no
// content change counts as no changed file in either format.
func TestAnalyzeDiff_RenameOnlyAgreesAcrossFormats(t *testing.T) {
	gitlab, err := AnalyzeDiff([]byte(`[{"old_path":"a.go","new_path":"b.go","renamed_file":true,"diff":""}]`), FormatGitLabJSON)
	require.NoError(t, err)
	unified, err := AnalyzeDiff([]byte("diff --git a/a.go b/b.go\nsimilarity index 100%\nrename from a.go\nrename to b.go\n"), FormatUnified)
	require.NoError(t, err)
	assert.Empty(t, gitlab.ByLanguage)
	assert.Empty(t, unified.ByLanguage)

	// Positive control: the same rename beside a modified Go file counts that
	// file, and only that file, in both formats.
	gitlab, err = AnalyzeDiff([]byte(`[{"old_path":"a.go","new_path":"b.go","renamed_file":true,"diff":""},`+
		`{"old_path":"c.go","new_path":"c.go","diff":"@@ -1 +1 @@\n-var x = 1\n+var x = 2\n"}]`), FormatGitLabJSON)
	require.NoError(t, err)
	unified, err = AnalyzeDiff([]byte("diff --git a/a.go b/a.go\nsimilarity index 100%\nrename from a.go\nrename to b.go\n"+
		"diff --git a/c.go b/c.go\n--- a/c.go\n+++ b/c.go\n@@ -1 +1 @@\n-var x = 1\n+var x = 2\n"), FormatUnified)
	require.NoError(t, err)
	for _, got := range []*EffectiveLOC{gitlab, unified} {
		require.Contains(t, got.ByLanguage, "Go")
		assert.Equal(t, 1, got.ByLanguage["Go"].FilesChanged)
		assert.Equal(t, int64(1), got.TotalSourceLinesAdded)
	}
}


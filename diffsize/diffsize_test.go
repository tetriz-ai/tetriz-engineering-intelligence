// unifiedNewFile is a unified diff that adds one new file holding lines.
func unifiedNewFile(path string, lines ...string) []byte {
	var b strings.Builder
	fmt.Fprintf(&b, "diff --git a/%s b/%s\n--- /dev/null\n+++ b/%s\n@@ -0,0 +1,%d @@\n", path, path, path, len(lines))
	for _, l := range lines {
		b.WriteString("+" + l + "\n")
	}
	return []byte(b.String())
}


// TestAnalyzeDiff_GoFileWithComments verifies that a normal Go file diff
// classifies as Go, and that scc correctly splits code / comment / blank.
func TestAnalyzeDiff_GoFileWithComments(t *testing.T) {
	diff := `diff --git a/main.go b/main.go
--- /dev/null
+++ b/main.go
@@ -0,0 +1,5 @@
+package main
+
+// main is the entry point.
+func main() {
+}
`
	result, err := AnalyzeDiff([]byte(diff), "unified")
	require.NoError(t, err)

	// 5 added lines total: package / blank / comment / func / }
	// We assert on the high-order invariants rather than brittle exact counts
	// (scc's blank/comment heuristics can vary slightly across versions).
	assert.Equal(t, "v2", result.AnalysisVersion, "the documented version, not just the constant")
	assert.Contains(t, result.ByLanguage, "Go")
	goDetail := result.ByLanguage["Go"]
	assert.Equal(t, 1, goDetail.FilesChanged)

	totalAccounted := goDetail.SourceLinesAdded + goDetail.CommentLinesAdded + goDetail.BlankLinesAdded
	assert.Equal(t, int64(5), totalAccounted, "scc should classify every added line")
	assert.GreaterOrEqual(t, goDetail.CommentLinesAdded, int64(1), "at least one comment line")
	assert.GreaterOrEqual(t, goDetail.BlankLinesAdded, int64(1), "at least one blank line")
	assert.GreaterOrEqual(t, goDetail.SourceLinesAdded, int64(1), "at least one code line")

	// Totals mirror the per-language breakdown.
	assert.Equal(t, goDetail.SourceLinesAdded, result.TotalSourceLinesAdded)
	assert.Equal(t, goDetail.CommentLinesAdded, result.TotalCommentLinesAdded)
	assert.Equal(t, goDetail.BlankLinesAdded, result.TotalBlankLinesAdded)
	assert.Equal(t, int64(0), result.TotalGeneratedLinesAdded)
	assert.Equal(t, int64(0), result.TotalVendorLinesAdded)
	assert.Empty(t, result.ExcludedFiles)
}


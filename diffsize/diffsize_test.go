// TestAnalyzeDiff_ModifiedGeneratedFileCountsAsSource pins a limit of reading
// a diff: go-enry sees only the added lines, so an edit to an existing
// generated file whose banner is outside the hunk counts as source. An
// exclude pattern for the path is the remedy.
func TestAnalyzeDiff_ModifiedGeneratedFileCountsAsSource(t *testing.T) {
	for _, path := range []string{"gen/foo.pb.go", "store/mock_store.go", "w/wire_gen.go"} {
		diff := "diff --git a/" + path + " b/" + path + "\n--- a/" + path + "\n+++ b/" + path +
			"\n@@ -120,3 +120,5 @@\n \ta := 1\n+\tb := 2\n+\tc := 3\n \treturn\n }\n"
		result, err := AnalyzeDiff([]byte(diff), FormatUnified)
		require.NoError(t, err)
		assert.Equal(t, int64(0), result.TotalGeneratedLinesAdded, path)
		assert.Empty(t, result.ExcludedFiles, path)
		require.Contains(t, result.ByLanguage, "Go", path)
		assert.Equal(t, int64(2), result.ByLanguage["Go"].SourceLinesAdded, path)

		excluded, err := AnalyzeDiffWithExcludes([]byte(diff), FormatUnified, []string{"*.pb.go", "mock_*.go", "wire_gen.go"})
		require.NoError(t, err)
		assert.Equal(t, []string{path}, excluded.ExcludedFiles)
		assert.Empty(t, excluded.ByLanguage, path)
	}
	py := "diff --git a/x_pb2.py b/x_pb2.py\n--- a/x_pb2.py\n+++ b/x_pb2.py\n@@ -40,2 +40,4 @@\n a = 1\n+b = 2\n+c = 3\n d = 4\n"
	result, err := AnalyzeDiff([]byte(py), FormatUnified)
	require.NoError(t, err)
	assert.Equal(t, int64(2), result.ByLanguage["Python"].SourceLinesAdded)
}

